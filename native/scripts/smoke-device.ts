import {join} from 'node:path';
import {mkdirSync,writeFileSync} from 'node:fs';
import {MirrorSession} from '../src/session';
import {Adb} from '../src/adb';
import {Packet} from '../src/protocol';
const root=process.cwd(),serial=process.argv[2]??'emulator-5554';
const adb=new Adb(join(root,'resources/adb/adb.exe'));
const session=new MirrorSession(serial,{maxSize:1280,fps:30,bitrate:4000000},adb,join(root,'resources'));
const frames:Packet[]=[];
session.on('log',message=>console.log('ANDROID',message));
session.on('video',(packet:Packet)=>{frames.push(packet);});
session.on('info',info=>console.log('VIDEO_INFO',info));
session.on('ended',reason=>console.log('ENDED',reason));
async function main(){
  mkdirSync('build/smoke',{recursive:true});
  await session.start();console.log('STARTED');
  session.startRecording(join(root,'build/smoke/device-'+Date.now()+'.mp4'));
  session.control({type:'key',code:3});
  await new Promise(r=>setTimeout(r,1500));
  await adb.shell(serial,['am','start','-a','android.settings.SETTINGS']);
  await new Promise(r=>setTimeout(r,1500));
  session.control({type:'touch',action:0,x:.5,y:.8});
  session.control({type:'touch',action:2,x:.5,y:.3});
  session.control({type:'touch',action:1,x:.5,y:.3});
  await new Promise(r=>setTimeout(r,2000));
  session.stopRecording();
  writeFileSync(join(root,'build/smoke/stream.h264'),Buffer.concat(frames.map(f=>f.data)));
  console.log(JSON.stringify({frames:frames.length,keyframes:frames.filter(f=>f.flags&1).length,config:frames.filter(f=>f.flags&2).length,bytes:frames.reduce((n,f)=>n+f.data.length,0)}));
  if(frames.length<5)throw Error('Insufficient video frames');
}
void main().catch(e=>{console.error(e);process.exitCode=1;}).finally(()=>session.stop());
